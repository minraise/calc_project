# 더하기 함수
def sum(a, b):
    return a + b


# 빼기 함수
def sub(a, b):
    return a - b


# 곱하기 함수
def mul(a, b):
    return a * b


def square(a):
    return a**2


def mod(a, b):
    return a % b


def div(a, b):
    if b == 0:
        return 0
    else:
        return a / b


def x3(a):
    return a**3
